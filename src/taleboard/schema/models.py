"""
Defines the validation models used in this application.
"""
from datetime import datetime

from pydantic import BaseModel, Field

from taleboard.schema.enums import PositionCell, SizeInFrame, Orientation, ShotSize, CameraAngle, ProjectStatus


class Character(BaseModel):
    """
    Represents a character in the story, as the application stores and the user can edit.

    Attributes:
        name: str - Full name of the character.
        description: str - A brief description of the character (generated by an LLM).
        aliases: list[str] - Other ways the story refers to this character. Defaults to [].
        appearance_reference: str - S3 key of the character's reference image. Defaults to None (no reference image generated yet).
    """
    name: str
    description: str
    aliases: list[str] = Field(default_factory=list)
    appearance_reference: str | None = None

class Location(BaseModel):
    """
    Represents a place in the story that shots take place in, as the application stores it.

    Attributes:
        name: str - Short name of the place.
        description: str - A brief visual description of the place, as it always looks (generated by an LLM).
        master_plate: str - S3 key of the location's master plate -- a wide, eye-level view every background of it is drawn from. Defaults to None (no master plate generated yet).
    """
    name: str
    description: str
    master_plate: str | None = None

class Region(BaseModel):
    """
    Represents a single character within a shot.

    Attributes:
        character_id: str - Unique identifier of the character who "owns" this region.
        position: PositionCell - Position of the region in the 3x3 grid.
        size: SizeInFrame - Size of the region in the frame.
        orientation: Orientation - Orientation of the generated character in the frame.
        action: str - Action being performed by the character -- renders as a pose.
    """
    character_id: str
    position: PositionCell
    size: SizeInFrame
    orientation: Orientation
    action: str

class Shot(BaseModel):
    """
    Represents one storyboard panel.

    Attributes:
        description: str - A brief description of what happens in the shot.
        location_id: str - Unique identifier of the location the shot takes place in. None for shots broken down before locations existed. Defaults to None.
        details: str - Small, visible changes to the location in this shot (eg:- "the desk drawer hangs open"). Defaults to "" (the location looks as described).
        regions: list[Region] - A list of character regions within the shot.
        paragraph_index: int - Identifies uniquely the paragraph from which this shot originated.
        shot_size: ShotSize - Framing of the shot.
        angle: CameraAngle - Camera angle of the shot.
        duration_s: float - Duration that the shot lasts for (in seconds).
        generated_frame: str - A path or URL to the generated shot image. Defaults to None.
        needs_review: bool - A review flag. If set True, a human needs to manually review this shot. Defaults to False -- we don't want a human to review a shot unless there is an error in parsing/rendering.
    """
    description: str
    location_id: str | None = None
    details: str = ""
    regions: list[Region]
    paragraph_index: int
    shot_size: ShotSize
    angle: CameraAngle
    duration_s: float
    generated_frame: str | None = None
    needs_review: bool = False


class Project(BaseModel):
    """
    Represents a full storyboard project.

    Attributes:
        project_id: str - Unique identifier of the project.
        name: str - Name of the project.
        created_at: datetime - When the project was created (UTC).
        status: ProjectStatus - The stage of the project's lifecycle the render job is on. Defaults to CREATED.
        job_id: str - ID of the current render job. Defaults to None (no story submitted yet).
        shot_count: int - Number of shots, once the breakdown is final. Defaults to None (breakdown not finished).
        error: str - Why the render job failed. Defaults to None.
        shots: list[Shot] - A list of shots that are in the project, in story order. Defaults to [].
        cast: dict[str,Character] - A mapping between each unique character ID and each character. Defaults to {}.
        locations: dict[str,Location] - A mapping between each unique location ID and each location. Defaults to {}.
    """
    project_id: str
    name: str
    created_at: datetime
    status: ProjectStatus = ProjectStatus.CREATED
    job_id: str | None = None
    shot_count: int | None = None
    error: str | None = None
    shots: list[Shot] = Field(default_factory=list)
    cast: dict[str, Character] = Field(default_factory=dict)
    locations: dict[str, Location] = Field(default_factory=dict)